/**
 * Registers the native messaging host with Chromium-based browsers.
 * Linux/macOS: JSON manifest in each browser's NativeMessagingHosts directory.
 * Windows: JSON manifest + HKCU registry key pointing at it (no admin needed).
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { HOST_NAME } from '../shared/protocol.js';
import { HOME_DIR } from './config.js';

/** Fixed by the "key" in extension/manifest.json, so the ID is the same on every machine. */
export const EXTENSION_ID = 'deoglpgghholljpmkibnmkcpflgihine';

const home = os.homedir();
const LINUX_DIRS: Record<string, string> = {
  chrome: '.config/google-chrome', 'chrome-beta': '.config/google-chrome-beta', chromium: '.config/chromium',
  edge: '.config/microsoft-edge', brave: '.config/BraveSoftware/Brave-Browser', 'chrome-for-testing': '.config/google-chrome-for-testing',
};
const MAC_DIRS: Record<string, string> = {
  chrome: 'Library/Application Support/Google/Chrome', chromium: 'Library/Application Support/Chromium',
  edge: 'Library/Application Support/Microsoft Edge', brave: 'Library/Application Support/BraveSoftware/Brave-Browser',
  'chrome-for-testing': 'Library/Application Support/Google/Chrome for Testing',
};
const WIN_KEYS: Record<string, string> = {
  chrome: 'HKCU\\Software\\Google\\Chrome\\NativeMessagingHosts', chromium: 'HKCU\\Software\\Chromium\\NativeMessagingHosts',
  edge: 'HKCU\\Software\\Microsoft\\Edge\\NativeMessagingHosts', brave: 'HKCU\\Software\\BraveSoftware\\Brave-Browser\\NativeMessagingHosts',
};

const cliPath = () => path.join(path.dirname(fileURLToPath(import.meta.url)), 'cli.js');

function writeLauncher(): string {
  fs.mkdirSync(HOME_DIR, { recursive: true, mode: 0o700 });
  if (process.platform === 'win32') {
    const p = path.join(HOME_DIR, 'walled-dlp-host.bat');
    fs.writeFileSync(p, `@echo off\r\n"${process.execPath}" "${cliPath()}" host %*\r\n`);
    return p;
  }
  const p = path.join(HOME_DIR, 'walled-dlp-host.sh');
  fs.writeFileSync(p, `#!/bin/sh\n# Generated by walled-dlp install. Chrome starts this as the native messaging host.\nexec "${process.execPath}" "${cliPath()}" host "$@"\n`, { mode: 0o755 });
  return p;
}

function manifest(launcher: string, extensionIds: string[]) {
  return {
    name: HOST_NAME,
    description: 'Walled DLP Guard desktop agent',
    path: launcher,
    type: 'stdio',
    allowed_origins: extensionIds.map((id) => `chrome-extension://${id}/`),
  };
}

export interface InstallOptions { browsers?: string[]; userDataDir?: string; extensionIds?: string[] }

export function install(opts: InstallOptions = {}): string[] {
  const launcher = writeLauncher();
  const ids = opts.extensionIds?.length ? opts.extensionIds : [EXTENSION_ID];
  const body = JSON.stringify(manifest(launcher, ids), null, 2);
  const written: string[] = [];
  const writeTo = (dir: string) => {
    fs.mkdirSync(dir, { recursive: true });
    const file = path.join(dir, `${HOST_NAME}.json`);
    fs.writeFileSync(file, body);
    written.push(file);
    return file;
  };
  if (opts.userDataDir) writeTo(path.join(opts.userDataDir, 'NativeMessagingHosts'));
  if (process.platform === 'win32') {
    const file = writeTo(path.join(HOME_DIR, 'native-host'));
    for (const [b, key] of Object.entries(WIN_KEYS)) {
      if (opts.browsers?.length && !opts.browsers.includes(b)) continue;
      execFileSync('reg', ['add', `${key}\\${HOST_NAME}`, '/ve', '/t', 'REG_SZ', '/d', file, '/f'], { stdio: 'ignore' });
      written.push(`${key}\\${HOST_NAME}`);
    }
  } else if (!opts.userDataDir || opts.browsers?.length) {
    const dirs = process.platform === 'darwin' ? MAC_DIRS : LINUX_DIRS;
    for (const [b, rel] of Object.entries(dirs)) {
      if (opts.browsers?.length && !opts.browsers.includes(b)) continue;
      writeTo(path.join(home, rel, 'NativeMessagingHosts'));
    }
  }
  return written;
}

export function uninstall(opts: InstallOptions = {}): string[] {
  const removed: string[] = [];
  const rm = (file: string) => { if (fs.existsSync(file)) { fs.rmSync(file); removed.push(file); } };
  if (opts.userDataDir) rm(path.join(opts.userDataDir, 'NativeMessagingHosts', `${HOST_NAME}.json`));
  if (process.platform === 'win32') {
    for (const key of Object.values(WIN_KEYS)) {
      try { execFileSync('reg', ['delete', `${key}\\${HOST_NAME}`, '/f'], { stdio: 'ignore' }); removed.push(key); } catch { /* not present */ }
    }
    rm(path.join(HOME_DIR, 'native-host', `${HOST_NAME}.json`));
  } else {
    const dirs = process.platform === 'darwin' ? MAC_DIRS : LINUX_DIRS;
    for (const rel of Object.values(dirs)) rm(path.join(home, rel, 'NativeMessagingHosts', `${HOST_NAME}.json`));
  }
  return removed;
}
